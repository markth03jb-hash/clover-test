"""16x16 pixel-art spell icons (scaled to 64x64) for Julius Novachrono's Time Grimoire: midnight blue, gold, ivory."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from icons import make

J = ((22, 30, 78), (4, 6, 22), (255, 200, 68), (244, 232, 190))

def clock(x0, y0, x1, y1, k='m'):
    cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
    return [(k, 'e', x0, y0, x1, y1), ('a', 'p', cx, y0 + 1), ('a', 'p', x1 - 1, cy), ('a', 'p', cx, y1 - 1), ('a', 'p', x0 + 1, cy)]

def man(x, y, k='a', outline=False):
    """A tiny standing figure, feet at (x, y)."""
    if outline:
        return [(k, 'R', x - 1, y - 9, x + 1, y - 7), (k, 'R', x - 2, y - 6, x + 2, y - 2), (k, 'l', x - 1, y - 1, x - 1, y), (k, 'l', x + 1, y - 1, x + 1, y)]
    return [(k, 'r', x - 1, y - 9, x + 1, y - 7), (k, 'r', x - 2, y - 6, x + 2, y - 2), (k, 'l', x - 1, y - 1, x - 1, y), (k, 'l', x + 1, y - 1, x + 1, y)]

